export enum ScheduleEntryType {
    VACATION = 'vacation',
    SICK_LEAVE = 'sick_leave',
    OVERTIME = 'overtime',
    EXTRA_DAY = 'extra_day',
}

export enum ScheduleStatus {
    PENDING = 'pending',
    APPROVED = 'approved',
    REJECTED = 'rejected',
}

export interface IScheduleEntry {
    id: string;
    userId: string;
    type: ScheduleEntryType;
    dateFrom: string;
    dateTo: string;
    startTime: string;
    endTime: string;
    status: ScheduleStatus;
    approvedBy?: string | null;
    note?: string | null;
    autoGenerated: boolean;
    createdAt: string;
    updatedAt: string;
}

export interface IPatternSlot {
    work: boolean;
    startTime?: string | null;
    endTime?: string | null;
}

export interface ISchedulePattern {
    id: string;
    userId: string;
    cycleLength: number;
    anchorDate: string;
    defaultStartTime: string;
    defaultEndTime: string;
    slots: IPatternSlot[];
    createdAt: string;
    updatedAt: string;
}
