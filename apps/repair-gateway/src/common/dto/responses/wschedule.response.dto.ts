import { ApiProperty } from '@nestjs/swagger';
import { ScheduleEntryType, ScheduleStatus } from '@asko/shared';

export class WScheduleRecordDto {
    id: string;
    userId: string;
    @ApiProperty({ enum: ScheduleEntryType, enumName: 'ScheduleEntryType' })
    type: ScheduleEntryType;
    dateFrom: string;
    dateTo: string;
    startTime: string;
    endTime: string;
    @ApiProperty({ enum: ScheduleStatus, enumName: 'ScheduleStatus' })
    status: ScheduleStatus;
    approvedBy?: string;
    note?: string;
    autoGenerated: boolean;
    createdAt: string;
    updatedAt: string;
}

export class PaginatedScheduleResponseDto {
    @ApiProperty({ type: [WScheduleRecordDto] })
    data: WScheduleRecordDto[];
    overallCount: number;
    page: number;
    limit: number;
}

export class PatternSlotDto {
    work: boolean;
    startTime?: string;
    endTime?: string;
}

export class SchedulePatternRecordDto {
    id: string;
    userId: string;
    cycleLength: number;
    anchorDate: string;
    defaultStartTime: string;
    defaultEndTime: string;
    @ApiProperty({ type: [PatternSlotDto] })
    slots: PatternSlotDto[];
    createdAt: string;
    updatedAt: string;
}

export class SchedulePatternListResponseDto {
    @ApiProperty({ type: [SchedulePatternRecordDto] })
    data: SchedulePatternRecordDto[];
}
