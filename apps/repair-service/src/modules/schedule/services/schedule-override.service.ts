import { Injectable } from '@nestjs/common';
import { CreateRequestContext, EntityManager } from '@mikro-orm/postgresql';
import { ScheduleOverride } from '../entities/schedule-override.entity';
import { ScheduleStatus } from '../entities/schedule-status.enum';
import type { CreateScheduleOverrideRequest, UpdateScheduleOverrideRequest, FindAllSchedulesRequest } from '@asko/proto';

function parseDate(value: string): Date {
    return new Date(value);
}

@Injectable()
export class ScheduleOverrideService {
    constructor(private readonly em: EntityManager) {}

    @CreateRequestContext()
    async create(data: CreateScheduleOverrideRequest): Promise<ScheduleOverride> {
        const entry = new ScheduleOverride();
        entry.userId = data.userId;
        entry.date = parseDate(data.date);
        entry.startTime = data.startTime;
        entry.endTime = data.endTime;
        entry.note = data.note || null;
        entry.status = ScheduleStatus.PENDING;
        entry.createdBy = data.actorId || null;
        await this.em.persistAndFlush(entry);
        return entry;
    }

    @CreateRequestContext()
    async findAll(query: FindAllSchedulesRequest): Promise<{ data: ScheduleOverride[]; overallCount: number; page: number; limit: number }> {
        const page = query.page || 1;
        const limit = query.limit || 20;
        const where: any = {};
        if (query.userId) where.userId = query.userId;
        if (query.status) where.status = query.status.includes(',') ? { $in: query.status.split(',') } : query.status;
        if (query.dateFrom) where.date = { ...where.date, $gte: parseDate(query.dateFrom) };
        if (query.dateTo) where.date = { ...where.date, $lte: parseDate(query.dateTo) };
        const orderBy: any = query.sortBy
            ? { [query.sortBy]: query.sortOrder === 'desc' ? 'DESC' : 'ASC' }
            : { date: 'DESC' };

        const [data, overallCount] = await this.em.findAndCount(ScheduleOverride, where, {
            orderBy,
            limit,
            offset: (page - 1) * limit,
        });
        return { data, overallCount, page, limit };
    }

    @CreateRequestContext()
    async findOne(id: string): Promise<ScheduleOverride> {
        return this.em.findOneOrFail(ScheduleOverride, { id });
    }

    @CreateRequestContext()
    async update(id: string, data: UpdateScheduleOverrideRequest): Promise<ScheduleOverride> {
        const entry = await this.em.findOneOrFail(ScheduleOverride, { id });
        if (data.startTime !== undefined && data.startTime !== '') entry.startTime = data.startTime;
        if (data.endTime !== undefined && data.endTime !== '') entry.endTime = data.endTime;
        if (data.note !== undefined) entry.note = data.note || null;
        await this.em.flush();
        return entry;
    }

    @CreateRequestContext()
    async delete(id: string): Promise<{ id: string; userId: string }> {
        const entry = await this.em.findOneOrFail(ScheduleOverride, { id });
        const snapshot = { id: entry.id, userId: entry.userId };
        await this.em.removeAndFlush(entry);
        return snapshot;
    }

    @CreateRequestContext()
    async approve(id: string, approvedBy: string): Promise<ScheduleOverride> {
        const entry = await this.em.findOneOrFail(ScheduleOverride, { id });
        entry.status = ScheduleStatus.APPROVED;
        entry.approvedBy = approvedBy;
        await this.em.flush();
        return entry;
    }

    @CreateRequestContext()
    async reject(id: string, approvedBy: string): Promise<ScheduleOverride> {
        const entry = await this.em.findOneOrFail(ScheduleOverride, { id });
        entry.status = ScheduleStatus.REJECTED;
        entry.approvedBy = approvedBy;
        await this.em.flush();
        return entry;
    }

    @CreateRequestContext()
    async recordExtraDay(userId: string, date: Date, startTime: string, endTime: string, requestId: string): Promise<ScheduleOverride> {
        const existing = await this.em.findOne(ScheduleOverride, {
            userId,
            date,
        });
        if (existing) return existing;

        const entry = new ScheduleOverride();
        entry.userId = userId;
        entry.date = date;
        entry.startTime = startTime;
        entry.endTime = endTime;
        entry.status = ScheduleStatus.APPROVED;
        entry.autoGenerated = true;
        entry.note = `Авто: назначение на выходной, заявка #${requestId.slice(0, 8)}`;
        await this.em.persistAndFlush(entry);
        return entry;
    }

    @CreateRequestContext()
    async findBlockingOverride(userId: string, todayStart: Date, todayEnd: Date): Promise<ScheduleOverride | null> {
        return this.em.findOne(ScheduleOverride, {
            userId,
            status: ScheduleStatus.APPROVED,
            date: { $gte: todayStart, $lte: todayEnd },
        });
    }

    @CreateRequestContext()
    async findTodayEntries(userId: string, todayStart: Date, todayEnd: Date): Promise<ScheduleOverride[]> {
        return this.em.find(ScheduleOverride, {
            userId,
            status: ScheduleStatus.APPROVED,
            date: { $gte: todayStart, $lte: todayEnd },
        });
    }

    @CreateRequestContext()
    async findInRange(userId: string, dateFrom: Date, dateTo: Date): Promise<ScheduleOverride[]> {
        return this.em.find(ScheduleOverride, {
            userId,
            status: ScheduleStatus.APPROVED,
            date: { $gte: dateFrom, $lte: dateTo },
        });
    }
}
