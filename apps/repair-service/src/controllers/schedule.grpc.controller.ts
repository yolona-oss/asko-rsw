import { Controller } from '@nestjs/common';
import { GrpcMethod, RpcException } from '@nestjs/microservices';
import { status } from '@grpc/grpc-js';
import { WScheduleService } from 'services/wschedule.service';
import { RepairEventService, RepairEventType } from 'modules/repair-event.service';
import type { WSchedule } from 'entities/wschedule.entity';
import type {
    CreateScheduleRequest,
    UpdateScheduleRequest,
    FindAllSchedulesRequest,
    ScheduleFindByIdRequest,
    ScheduleDeleteRequest,
    ScheduleApproveRequest,
    ScheduleRecord,
    ScheduleResponse,
    SchedulePaginatedResponse,
    ScheduleEmptyResponse,
} from '@asko/proto';

function formatDate(d: Date): string {
    return d.toISOString().split('T')[0];
}

function toRecord(entry: WSchedule): ScheduleRecord {
    return {
        id: entry.id,
        userId: entry.userId,
        type: entry.type,
        dateFrom: formatDate(entry.dateFrom),
        dateTo: formatDate(entry.dateTo),
        startTime: entry.startTime,
        endTime: entry.endTime,
        status: entry.status,
        approvedBy: entry.approvedBy ?? '',
        note: entry.note ?? '',
        autoGenerated: entry.autoGenerated,
        createdAt: entry.createdAt.toISOString(),
        updatedAt: entry.updatedAt.toISOString(),
    };
}

@Controller()
export class ScheduleGrpcController {
    constructor(
        private readonly scheduleService: WScheduleService,
        private readonly repairEventService: RepairEventService,
    ) {}

    @GrpcMethod('ScheduleService', 'CreateSchedule')
    async createSchedule(data: CreateScheduleRequest): Promise<ScheduleResponse> {
        try {
            const entry = await this.scheduleService.create(data);
            await this.repairEventService.emitScheduleEvent({
                type: RepairEventType.SCHEDULE_CREATED,
                scheduleId: entry.id,
                userId: entry.userId,
                scheduleType: entry.type,
                timestamp: new Date(),
            });
            return { schedule: toRecord(entry) };
        } catch (e) {
            throw new RpcException({ code: status.INTERNAL, message: e instanceof Error ? e.message : 'Internal error' });
        }
    }

    @GrpcMethod('ScheduleService', 'UpdateSchedule')
    async updateSchedule(data: UpdateScheduleRequest): Promise<ScheduleResponse> {
        try {
            const entry = await this.scheduleService.update(data.id, data);
            await this.repairEventService.emitScheduleEvent({
                type: RepairEventType.SCHEDULE_UPDATED,
                scheduleId: entry.id,
                userId: entry.userId,
                scheduleType: entry.type,
                timestamp: new Date(),
            });
            return { schedule: toRecord(entry) };
        } catch (e) {
            if (e instanceof RpcException) throw e;
            throw new RpcException({ code: status.INTERNAL, message: e instanceof Error ? e.message : 'Internal error' });
        }
    }

    @GrpcMethod('ScheduleService', 'FindAllSchedules')
    async findAllSchedules(data: FindAllSchedulesRequest): Promise<SchedulePaginatedResponse> {
        try {
            const result = await this.scheduleService.findAll(data);
            return {
                data: result.data.map(toRecord),
                overallCount: result.overallCount,
                page: result.page,
                limit: result.limit,
            };
        } catch (e) {
            throw new RpcException({ code: status.INTERNAL, message: e instanceof Error ? e.message : 'Internal error' });
        }
    }

    @GrpcMethod('ScheduleService', 'FindScheduleById')
    async findScheduleById(data: ScheduleFindByIdRequest): Promise<ScheduleResponse> {
        try {
            const entry = await this.scheduleService.findOne(data.id);
            return { schedule: toRecord(entry) };
        } catch (e) {
            if (e instanceof RpcException) throw e;
            throw new RpcException({ code: status.NOT_FOUND, message: 'Schedule not found' });
        }
    }

    @GrpcMethod('ScheduleService', 'DeleteSchedule')
    async deleteSchedule(data: ScheduleDeleteRequest): Promise<ScheduleEmptyResponse> {
        try {
            await this.scheduleService.delete(data.id);
            return {};
        } catch (e) {
            throw new RpcException({ code: status.INTERNAL, message: e instanceof Error ? e.message : 'Internal error' });
        }
    }

    @GrpcMethod('ScheduleService', 'ApproveSchedule')
    async approveSchedule(data: ScheduleApproveRequest): Promise<ScheduleResponse> {
        try {
            const entry = await this.scheduleService.approve(data.id, data.approvedBy);
            await this.repairEventService.emitScheduleEvent({
                type: RepairEventType.SCHEDULE_APPROVED,
                scheduleId: entry.id,
                userId: entry.userId,
                actorId: data.approvedBy,
                scheduleType: entry.type,
                timestamp: new Date(),
            });
            return { schedule: toRecord(entry) };
        } catch (e) {
            if (e instanceof RpcException) throw e;
            throw new RpcException({ code: status.INTERNAL, message: e instanceof Error ? e.message : 'Internal error' });
        }
    }

    @GrpcMethod('ScheduleService', 'RejectSchedule')
    async rejectSchedule(data: ScheduleApproveRequest): Promise<ScheduleResponse> {
        try {
            const entry = await this.scheduleService.reject(data.id, data.approvedBy);
            await this.repairEventService.emitScheduleEvent({
                type: RepairEventType.SCHEDULE_REJECTED,
                scheduleId: entry.id,
                userId: entry.userId,
                actorId: data.approvedBy,
                scheduleType: entry.type,
                timestamp: new Date(),
            });
            return { schedule: toRecord(entry) };
        } catch (e) {
            if (e instanceof RpcException) throw e;
            throw new RpcException({ code: status.INTERNAL, message: e instanceof Error ? e.message : 'Internal error' });
        }
    }
}
